def test_cloud_ftp_base_transport():
    # Instantiate the base transport.
    with mock.patch(
        "google.cloud.ftp_v1.services.cloud_ftp.transports.CloudFtpTransport.__init__"
    ) as Transport:
        Transport.return_value = None
        transport = transports.CloudFtpTransport(
            credentials=ga_credentials.AnonymousCredentials(),
        )

    # Every method on the transport should just blindly
    # raise NotImplementedError.
    methods = (
        "list_servers",
        "get_server",
        "create_server",
        "update_server",
        "delete_server",
        "list_users",
        "get_user",
        "create_user",
        "update_user",
        "delete_user",
        "start_server",
        "stop_server",
        "get_location",
        "list_locations",
        "get_operation",
        "cancel_operation",
        "delete_operation",
        "list_operations",
    )
    for method in methods:
        with pytest.raises(NotImplementedError):
            getattr(transport, method)(request=object())

    with pytest.raises(NotImplementedError):
        transport.close()

    # Additionally, the LRO client (a property) should
    # also raise NotImplementedError
    with pytest.raises(NotImplementedError):
        transport.operations_client

    # Catch all for all remaining methods and properties
    remainder = [
        "kind",
    ]
    for r in remainder:
        with pytest.raises(NotImplementedError):
            getattr(transport, r)()


