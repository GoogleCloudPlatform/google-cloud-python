class SpacesServiceClientMeta(type):
    """Metaclass for the SpacesService client.

    This provides class-level methods for building and retrieving
    support objects (e.g. transport) without polluting the client instance
    objects.
    """

    _transport_registry = OrderedDict()  # type: Dict[str, Type[SpacesServiceTransport]]
    _transport_registry["grpc"] = SpacesServiceGrpcTransport
    _transport_registry["grpc_asyncio"] = SpacesServiceGrpcAsyncIOTransport
    _transport_registry["rest"] = SpacesServiceRestTransport

    def get_transport_class(
        cls,
        label: Optional[str] = None,
    ) -> Type[SpacesServiceTransport]:
        """Returns an appropriate transport class.

        Args:
            label: The name of the desired transport. If none is
                provided, then the first transport in the registry is used.

        Returns:
            The transport class to use.
        """
        # If a specific transport is requested, return that one.
        if label:
            return cls._transport_registry[label]

        # No transport is requested; return the default (that is, the first one
        # in the dictionary).
        return next(iter(cls._transport_registry.values()))


